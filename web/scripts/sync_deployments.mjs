// Copies contracts/deployments/<chain_id>.json into src/generated/deployments.json and writes
// src/generated/abi.ts from the Foundry artifacts. Chain id comes from NEXT_PUBLIC_CHAIN_ID (default 31337).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web_root = resolve(here, '..');
const contracts_root = resolve(web_root, '..', 'contracts');
const chain_id = process.env.NEXT_PUBLIC_CHAIN_ID ?? '31337';
const dep_src = join(contracts_root, 'deployments', `${chain_id}.json`);
const gen_dir = join(web_root, 'src', 'generated');
mkdirSync(gen_dir, { recursive: true });

if (!existsSync(dep_src)) {
  throw new Error(`deployments file missing: ${dep_src}`);
}
copyFileSync(dep_src, join(gen_dir, 'deployments.json'));

const artifact_of = (file, name) => {
  const p = join(contracts_root, 'out', file, `${name}.json`);
  if (!existsSync(p)) throw new Error(`artifact missing (run forge build): ${p}`);
  return JSON.parse(readFileSync(p, 'utf8')).abi;
};

const abis = {
  manager: artifact_of('StudyStakeManager.sol', 'StudyStakeManager'),
  badge: artifact_of('StudyBadge.sol', 'StudyBadge'),
  vault: artifact_of('MockYieldVault.sol', 'MockYieldVault'),
  erc20: artifact_of('TestUSDC.sol', 'TestUSDC'),
};

const body = `// AUTO-GENERATED by web/scripts/sync_deployments.mjs from contracts/out. Do not edit.
export const manager_abi = ${JSON.stringify(abis.manager, null, 2)} as const;
export const badge_abi = ${JSON.stringify(abis.badge, null, 2)} as const;
export const vault_abi = ${JSON.stringify(abis.vault, null, 2)} as const;
export const token_abi = ${JSON.stringify(abis.erc20, null, 2)} as const;
`;
writeFileSync(join(gen_dir, 'abi.ts'), body);
console.log(`sync_deployments: chain ${chain_id} -> src/generated (manager, badge, vault, token ABIs)`);
