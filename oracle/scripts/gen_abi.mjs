// Extracts the StudyStakeManager ABI from Foundry output into src/abi/manager.ts (as const).
// Usage: node scripts/gen_abi.mjs            (reads existing contracts/out)
//        node scripts/gen_abi.mjs --build    (runs `forge build` in contracts/ first)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const oracle_root = resolve(here, '..');
const contracts_root = resolve(oracle_root, '..', 'contracts');
const artifact_path = join(contracts_root, 'out', 'StudyStakeManager.sol', 'StudyStakeManager.json');
const out_path = join(oracle_root, 'src', 'abi', 'manager.ts');

if (process.argv.includes('--build')) {
  const env = { ...process.env, PATH: `${process.env.PATH}${process.platform === 'win32' ? ';' : ':'}${process.env.HOME ?? process.env.USERPROFILE}/.foundry/bin` };
  execFileSync('forge', ['build'], { cwd: contracts_root, stdio: 'inherit', env, shell: process.platform === 'win32' });
}

const artifact = JSON.parse(readFileSync(artifact_path, 'utf8'));
const abi = artifact.abi;
if (!Array.isArray(abi)) throw new Error(`no abi array in ${artifact_path}`);

const has_collect = abi.some((item) => item.type === 'function' && item.name === 'collect_treasury');

mkdirSync(dirname(out_path), { recursive: true });
const body = `// AUTO-GENERATED by scripts/gen_abi.mjs from contracts/out/StudyStakeManager.sol/StudyStakeManager.json. Do not edit.
export const manager_abi = ${JSON.stringify(abi, null, 2)} as const;
export const manager_has_collect_treasury = ${has_collect} as const;
`;
writeFileSync(out_path, body);
console.log(`wrote ${out_path} (${abi.length} entries, collect_treasury: ${has_collect})`);
